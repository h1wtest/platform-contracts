#!/usr/bin/env python3
"""Generate strict Go/Rust/TypeScript wire codecs, OpenAPI and artifact inventory."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORMATS = {'uuid','uuid-v7','date-time','usdt6','usdt6-total','decimal','sha256','traceparent','encrypted'}
SUPPORTED = {'type','$ref','properties','required','additionalProperties','items','enum','const','format','minLength','maxLength','minimum','maximum','minItems','maxItems','anyOf','title','description','$comment'}

def check_rule(rule):
    unknown = rule.keys() - SUPPORTED
    if unknown:
        raise ValueError(f'Unsupported schema constraints: {sorted(unknown)}')
    if rule.get('format') not in FORMATS | {None}:
        raise ValueError('Unsupported format')
    if rule.get('type') == 'object' and rule.get('additionalProperties') is not False:
        raise ValueError('Objects must forbid unknown fields')
    if '$ref' in rule and (not rule['$ref'].startswith('#/$defs/') or rule.keys() - {'$ref','title','description','$comment'}):
        raise ValueError('Unsupported reference or reference sibling')
    if 'anyOf' in rule and (len(rule['anyOf']) != 2 or rule['anyOf'][1] != {'type':'null'} or '$ref' not in rule['anyOf'][0]):
        raise ValueError('Only nullable reference anyOf supported')
    kinds=rule.get('type')
    if isinstance(kinds,list) and (len(kinds)!=2 or 'null' not in kinds):raise ValueError('Only nullable type unions supported')
    scalar=kind(rule)
    if scalar not in (None,'null','string','object','array','boolean','integer'):raise ValueError('Unsupported wire type')
    for keyword in ('minimum','maximum'):
        if keyword in rule and (scalar!='integer' or type(rule[keyword]) is not int):raise ValueError('Integer bounds require integers')
    if 'enum' in rule and (scalar!='string' or not rule['enum'] or not all(isinstance(v,str) or v is None and isinstance(kinds,list) and 'null' in kinds for v in rule['enum'])):raise ValueError('Only string/nullable string enums supported')
    if 'required' in rule and (scalar!='object' or set(rule['required'])-rule.get('properties',{}).keys()):raise ValueError('Invalid required properties')
    if scalar=='array' and 'items' not in rule:raise ValueError('Array items required')
    if '$ref' not in rule and 'anyOf' not in rule and scalar is None:raise ValueError('Explicit schema type required')
    for child in rule.get('properties',{}).values():
        check_rule(child)
    if 'items' in rule:
        check_rule(rule['items'])
    for child in rule.get('anyOf',[]):
        check_rule(child)

def name(field):
    return ''.join({'id':'ID','ip':'IP','mfa':'MFA','csrf':'CSRF','url':'URL','oauth':'OAuth'}.get(p,p.title()) for p in field.split('_'))

def nullable(rule):
    return 'anyOf' in rule or isinstance(rule.get('type'),list)

def kind(rule):
    k=rule.get('type')
    return next((v for v in k if v!='null'),None) if isinstance(k,list) else k

def typ(rule,lang):
    if 'anyOf' in rule:
        return typ(rule['anyOf'][0],lang)
    if '$ref' in rule:
        return rule['$ref'].split('/')[-1]
    if kind(rule)=='array':
        t=typ(rule['items'],lang)
        return {'go':'[]'+t,'rust':'Vec<'+t+'>','ts':'Array<'+t+'>'}[lang]
    if lang=='ts' and 'enum' in rule:
        return ' | '.join(json.dumps(v) for v in rule['enum'] if v is not None)
    if lang=='ts' and kind(rule)=='integer' and (rule.get('maximum',0)>9007199254740991 or rule.get('minimum',0)<-9007199254740991):return 'number | bigint'
    if lang=='go' and rule.get('format')=='date-time':return 'time.Time'
    if lang=='rust' and rule.get('format') in ('uuid','uuid-v7'):return 'uuid::Uuid'
    if lang=='rust' and rule.get('format')=='date-time':return 'chrono::DateTime<chrono::Utc>'
    return {'go':{'string':'string','integer':'int64','boolean':'bool'},'rust':{'string':'String','integer':'i64','boolean':'bool'},'ts':{'string':'string','integer':'number','boolean':'boolean'}}[lang][kind(rule)]

def typescript_literal(value):
    if isinstance(value,dict):return '{'+','.join(json.dumps(k)+':'+typescript_literal(v) for k,v in value.items())+'}'
    if isinstance(value,list):return '['+','.join(typescript_literal(v) for v in value)+']'
    if type(value) is int and abs(value)>9007199254740991:return str(value)+'n'
    return json.dumps(value,separators=(',',':'))

def write(path,text):
    p=ROOT/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text,encoding='utf-8',newline='\n')

def generate_schema(stem,pkg):
    schema=json.loads((ROOT/f'schema/{stem}.json').read_text())
    defs=schema['$defs']
    for rule in defs.values():check_rule(rule)
    canonical=json.dumps(schema,separators=(',',':'))
    go=['// Code generated by scripts/generate_v2.py; DO NOT EDIT.','package '+pkg,'import ("encoding/json"; "time"; "platform-contracts/gen/go/wire")','var _ = time.Time{}','const CanonicalSchema = `'+canonical+'`','var registry = wire.Schema(CanonicalSchema)','func Validate(name string,data []byte) error { return registry.Validate(name,data) }']
    rs=['// Code generated by scripts/generate_v2.py; DO NOT EDIT.','use serde::{Serialize,Deserialize};','pub const CANONICAL_SCHEMA: &str = r###"'+canonical+'"###;','pub fn validate(name:&str,value:&serde_json::Value)->Result<(),String>{crate::validation_v2::validate(CANONICAL_SCHEMA,name,value)}']
    ts=['// Code generated by scripts/generate_v2.py; DO NOT EDIT.','import {validate,parseStrictJSON,stringifyStrictJSON} from "./validation.js";' if pkg=='eventsv2' else 'import {validate} from "./validation.js";','export const schema = '+typescript_literal(schema)+' as const;']
    shared=json.loads((ROOT/'schema/business-v1.json').read_text())['$defs'] if pkg!='businessv1' else {}
    if shared:go[2]=go[2][:-1]+'; "platform-contracts/gen/go/businessv1")'
    for n,rule in defs.items():
        go_start=len(go)
        if kind(rule)=='array':
            go+=['type '+n+' '+typ(rule,'go')]
            array_type=typ(rule,'rust')
            rs+=['#[derive(Debug,Clone)]','pub struct '+n+'('+array_type+');',
                 'impl '+n+'{pub fn new(value:'+array_type+')->Result<Self,String>{let raw=serde_json::to_value(&value).map_err(|e|e.to_string())?;validate("'+n+'",&raw)?;Ok(Self(value))}pub fn as_slice(&self)->&['+typ(rule['items'],'rust')+']{&self.0}pub fn into_inner(self)->'+array_type+'{self.0}pub fn validate(&self)->Result<(),String>{let raw=serde_json::to_value(&self.0).map_err(|e|e.to_string())?;validate("'+n+'",&raw)}}',
                 'impl TryFrom<'+array_type+'> for '+n+'{type Error=String;fn try_from(value:'+array_type+')->Result<Self,String>{Self::new(value)}}',
                 'impl Serialize for '+n+'{fn serialize<S:serde::Serializer>(&self,s:S)->Result<S::Ok,S::Error>{self.validate().map_err(serde::ser::Error::custom)?;self.0.serialize(s)}}',
                 "impl<'de> Deserialize<'de> for "+n+"{fn deserialize<D:serde::Deserializer<'de>>(d:D)->Result<Self,D::Error>{let crate::validation_v2::UniqueValue(value)=crate::validation_v2::UniqueValue::deserialize(d)?;validate(\""+n+'\",&value).map_err(serde::de::Error::custom)?;let items=serde_json::from_value(value).map_err(serde::de::Error::custom)?;Ok(Self(items))}}']
            ts+=['export type '+n+' = '+typ(rule,'ts')+';']
        else:
            go+=['type '+n+' struct {'];rs+=['#[derive(Debug,Clone)]','pub struct '+n+' {'];ts+=['export interface '+n+' {']
            for field,r in rule['properties'].items():
                optional=field not in rule.get('required',[]);nu=nullable(r)
                gt=typ(r,'go');rt=typ(r,'rust');tt=typ(r,'ts')
                suffix=',omitempty' if optional else ''
                if optional and nu:
                    gt='wire.Optional['+gt+']';rt='Option<Option<'+rt+'>>';suffix=',omitzero'
                elif optional or nu:gt='*'+gt;rt='Option<'+rt+'>'
                go+=[name(field)+' '+gt+' `json:"'+field+suffix+'"`']
                rs+=['pub '+field+': '+rt+',']
                ts+=[field+('?' if optional else '')+': '+tt+(' | null' if nu else '')+';']
            go+=['}'];rs+=['}'];ts+=['}']
            if not rule['properties']:ts[-2:]=['export type '+n+' = Record<string, never>;']
            mutable='mut ' if rule['properties'] else ''
            rs+=['impl '+n+' { pub fn validate(&self)->Result<(),String>{let value=self.wire_value().map_err(|e|e.to_string())?;validate("'+n+'",&value)}','fn wire_value(&self)->Result<serde_json::Value,serde_json::Error>{let '+mutable+'fields=serde_json::Map::new();']
            for field,field_rule in rule['properties'].items():
                copy_leaf=typ(field_rule,'rust') in ('i64','bool','uuid::Uuid','chrono::DateTime<chrono::Utc>')
                borrow='' if copy_leaf else '&'
                if field not in rule.get('required',[]):
                    rs+=['if let Some(value)='+borrow+'self.'+field+'{fields.insert("'+field+'".into(),serde_json::to_value(value)?);}']
                else:
                    rs+=['fields.insert("'+field+'".into(),serde_json::to_value('+borrow+'self.'+field+')?);']
            rs+=['Ok(serde_json::Value::Object(fields))}}','impl Serialize for '+n+'{fn serialize<S:serde::Serializer>(&self,s:S)->Result<S::Ok,S::Error>{let value=self.wire_value().map_err(serde::ser::Error::custom)?;validate("'+n+'",&value).map_err(serde::ser::Error::custom)?;value.serialize(s)}}',"impl<'de> Deserialize<'de> for "+n+" { fn deserialize<D:serde::Deserializer<'de>>(d:D)->Result<Self,D::Error>{",'let crate::validation_v2::UniqueValue(value)=crate::validation_v2::UniqueValue::deserialize(d)?;validate("'+n+'",&value).map_err(serde::de::Error::custom)?;','#[derive(Deserialize)] #[serde(deny_unknown_fields)] struct Wire {']
            for field,r in rule['properties'].items():
                rt=typ(r,'rust');optional=field not in rule.get('required',[])
                if optional and nullable(r):
                    rt='Option<Option<'+rt+'>>'
                    rs+=['#[serde(default,deserialize_with="crate::validation_v2::present_nullable")]']
                elif optional or nullable(r):rt='Option<'+rt+'>'
                rs+=[field+': '+rt+',']
            binding='w' if rule['properties'] else '_w'
            rs+=['}','let '+binding+':Wire=serde_json::from_value(value).map_err(serde::de::Error::custom)?;','Ok(Self{'+','.join(f+':w.'+f for f in rule['properties'])+'})}}']
        go+=['func(v '+n+') Validate()error {type alias '+n+';data,err:=json.Marshal(alias(v));if err!=nil{return err};return Validate("'+n+'",data)}','func(v '+n+') MarshalJSON()([]byte,error){type alias '+n+';data,err:=json.Marshal(alias(v));if err!=nil{return nil,err};if err=Validate("'+n+'",data);err!=nil{return nil,err};return data,nil}','func(v *'+n+') UnmarshalJSON(data []byte)error{if err:=Validate("'+n+'",data);err!=nil{return err};type alias '+n+';var a alias;if err:=json.Unmarshal(data,&a);err!=nil{return err};*v='+n+'(a);return nil}']
        ts+=['export function decode'+n+'(value:unknown): '+n+' {validate(schema,"'+n+'",value);return value as '+n+';}']
        if n in shared and rule==shared[n]:go[go_start:]=['type '+n+' = businessv1.'+n]
    write('gen/go/'+pkg+'/types.go','\n'.join(go)+'\n');write('rust/src/'+pkg+'_types.rs','\n'.join(rs)+'\n');write('gen/typescript/'+pkg+'.ts','\n'.join(ts)+'\n')
    return schema

def openapi(schema,public):
    doc={'openapi':'3.1.0','info':{'title':'Platform '+('public business' if public else 'internal workload')+' API','version':'1.0.0' if public else '2.0.0'},'paths':{},'components':{'schemas':schema['$defs'],'securitySchemes':{'Session':{'type':'apiKey','in':'cookie','name':'sso_session'},'ServiceToken':{'type':'apiKey','in':'header','name':'X-Service-Token'}}}}
    for endpoint in schema['x-endpoints']:
        statuses=endpoint['x-success-statuses']
        if not statuses or len(set(statuses))!=len(statuses) or any(type(code) is not int or code not in (200,201,202,204) for code in statuses):raise ValueError('Explicit supported success statuses required')
        responses={str(code):({'description':'Success'} if code==204 else {'description':'Success','content':{'application/json':{'schema':{'$ref':'#/components/schemas/'+endpoint['response']}}}}) for code in statuses}
        responses.update({str(c):{'description':d,'content':{'application/json':{'schema':{'$ref':'#/components/schemas/ErrorResponse'}}}} for c,d in [(400,'Invalid request'),(401,'Unauthenticated'),(403,'Forbidden'),(404,'Not found'),(409,'Conflict'),(503,'Dependency unavailable')]})
        operation={'operationId':endpoint['method'].lower()+'_'+endpoint['path'].strip('/').replace('/','_').replace('{','').replace('}','').replace('-','_'),'security':[] if endpoint.get('x-anonymous') else [{'Session' if public else 'ServiceToken':[]}],'responses':responses,'x-success-statuses':statuses}
        for field in ('permission_policy','callers','x-not-found-policy'):
            if field in endpoint:operation[field if field.startswith('x-') else 'x-'+field.replace('_','-')]=endpoint[field]
        import re
        operation['parameters']=[{'name':p,'in':'path','required':True,'schema':{'type':'string'}} for p in re.findall(r'\{([^}]+)\}',endpoint['path'])]
        if 'permission' in endpoint:operation['x-permission']=endpoint['permission'];operation['x-fresh-mfa']=True
        if 'request' in endpoint:operation['requestBody']={'required':True,'content':{'application/json':{'schema':{'$ref':'#/components/schemas/'+endpoint['request']}}}}
        doc['paths'].setdefault(endpoint['path'],{})[endpoint['method'].lower()]=operation
    # Rewrite bundled local references for OpenAPI components.
    return json.loads(json.dumps(doc).replace('#/$defs/','#/components/schemas/'))

def generate():
    business=generate_schema('business-v1','businessv1');internal=generate_schema('internal-http-v2','internalhttpv2');events=generate_schema('events-v2','eventsv2')
    entries=events['x-events']
    write('gen/go/eventsv2/registry.go','// Code generated; DO NOT EDIT.\npackage eventsv2\ntype eventRule struct{Definition,Producer,AggregateType,Topic string;Encrypted bool;AggregateField string}\nvar eventRules=map[string]eventRule{\n'+''.join(json.dumps(k)+':{'+','.join(json.dumps(v[x]) for x in ['definition','producer','aggregate_type','topic'])+','+str(v['encrypted']).lower()+','+json.dumps(v['x-aggregate-field'])+'},\n' for k,v in entries.items())+'}\n')
    write('rust/src/eventsv2_registry.rs','// Code generated; DO NOT EDIT.\npub fn event_rule(t:&str)->Option<(&\'static str,&\'static str,&\'static str,&\'static str,bool,&\'static str)>{match t{'+''.join(json.dumps(k)+'=>Some(('+','.join(json.dumps(v[x]) for x in ['definition','producer','aggregate_type','topic'])+','+str(v['encrypted']).lower()+','+json.dumps(v['x-aggregate-field'])+')),' for k,v in entries.items())+'_=>None}}\n')
    envelope=[]
    for event_type,event in entries.items():
        properties=dict(events['properties'])
        properties.pop('payload');properties.pop('encrypted_payload')
        body='encrypted_payload' if event['encrypted'] else 'payload'
        properties[body]=events['properties'][body] if event['encrypted'] else {'$ref':'#/$defs/'+event['definition']}
        envelope.append((event_type,{'type':'object','additionalProperties':False,'required':events['required']+[body],'properties':properties}))
    event_schema=dict(events);event_schema['$defs']={**events['$defs'],**dict(envelope)}
    event_canonical=typescript_literal(event_schema)
    variants=[]
    for event_type,event in entries.items():
        variants.append('{schema_version:2;event_id:string;event_type:'+json.dumps(event_type)+';producer:'+json.dumps(event['producer'])+';aggregate_type:'+json.dumps(event['aggregate_type'])+';aggregate_id:string;aggregate_version:number|bigint;occurred_at:string;correlation_id?:string;causation_id?:string;traceparent?:string;'+('encrypted_payload:string;payload?:never' if event['encrypted'] else 'payload:'+event['definition']+';encrypted_payload?:never')+'}')
    with (ROOT/'gen/typescript/eventsv2.ts').open('a',encoding='utf-8',newline='\n') as f:
        f.write('\nexport type Envelope = '+' | '.join(variants)+';\nconst envelopeSchema = '+event_canonical+' as const;\nexport function decodeEnvelope(value:unknown):Envelope {if(typeof value!=="object"||value===null||!("event_type" in value)||typeof value.event_type!=="string")throw new TypeError("Event type required");validate(envelopeSchema,value.event_type,value);const e=value as Envelope;const rule=schema["x-events"][e.event_type];if(!rule||e.producer!==rule.producer||e.aggregate_type!==rule.aggregate_type)throw new TypeError("Event producer mismatch");const field=rule["x-aggregate-field"];if(field&&((e.payload as unknown as Record<string,unknown>)[field]!==e.aggregate_id))throw new TypeError("Payload aggregate mismatch");if((rule.encrypted||e.aggregate_type==="external_event")&&(e.aggregate_id!==e.event_id||BigInt(e.aggregate_version)!==1n))throw new TypeError("Independent aggregate mismatch");return e;}\n')
        f.write('export function parseEnvelope(text:string):Envelope{return decodeEnvelope(parseStrictJSON(text));}\nexport function stringifyEnvelope(value:Envelope):string{return stringifyStrictJSON(decodeEnvelope(value));}\n')
    for public,schema in [(True,business),(False,internal)]:write('openapi/'+('public-v1' if public else 'internal-v2')+'.json',json.dumps(openapi(schema,public),indent=2)+'\n')
    files=sorted([*ROOT.glob('schema/*.json'),*ROOT.glob('openapi/*.json')])
    manifest={'contract_version':2,'files':{p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in files}}
    write('release-manifest.json',json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':generate()
