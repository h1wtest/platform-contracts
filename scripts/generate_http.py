#!/usr/bin/env python3
"""Generate internal HTTP DTOs and strict codecs from the canonical schema."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def name(field):
    return ''.join({'id': 'ID', 'ip': 'IP', 'mfa': 'MFA', 'csrf': 'CSRF'}.get(part, part.title()) for part in field.split('_'))

def nullable(rule):
    return isinstance(rule.get('type'), list) and 'null' in rule['type']

def kind(rule):
    value = rule.get('type')
    return next((value for value in value if value != 'null'), None) if isinstance(value, list) else value

def go_type(rule):
    if '$ref' in rule:
        return 'json.RawMessage' if rule['$ref'] == 'events-v1.json' else rule['$ref'].split('/')[-1]
    if kind(rule) == 'array':
        return '[]' + go_type(rule['items'])
    if rule.get('format') == 'date-time':
        return 'time.Time'
    return {'string': 'string', 'boolean': 'bool', 'integer': 'int64'}[kind(rule)]

def rust_type(rule):
    if '$ref' in rule:
        return 'crate::Envelope' if rule['$ref'] == 'events-v1.json' else rule['$ref'].split('/')[-1]
    if kind(rule) == 'array':
        return 'Vec<' + rust_type(rule['items']) + '>'
    if rule.get('format') == 'date-time':
        return 'DateTime<Utc>'
    if rule.get('format') == 'uuid':
        return 'Uuid'
    return {'string': 'String', 'boolean': 'bool', 'integer': 'i64'}[kind(rule)]

def check_rule(rule):
    supported = {'type', '$ref', 'properties', 'required', 'additionalProperties', 'items', 'enum', 'format', 'minLength', 'maxLength', 'minimum', 'title', 'description', '$comment'}
    unknown = rule.keys() - supported
    if unknown:
        raise ValueError(f'Unsupported HTTP schema constraints: {sorted(unknown)}')
    if 'enum' in rule and (kind(rule) != 'string' or not all(isinstance(value, str) for value in rule['enum'])):
        raise ValueError('HTTP enums must contain strings')
    if 'minimum' in rule and (kind(rule) != 'integer' or not isinstance(rule['minimum'], int)):
        raise ValueError('HTTP minima must be integers')
    if '$ref' in rule and rule.keys() - {'$ref', 'title', 'description', '$comment'}:
        raise ValueError('HTTP references cannot silently ignore sibling constraints')
    if isinstance(rule.get('type'), list) and (len(rule['type']) != 2 or 'null' not in rule['type']):
        raise ValueError('Only nullable HTTP type unions are supported')
    if kind(rule) == 'object' and rule.get('additionalProperties') is not False:
        raise ValueError('HTTP objects must deny unknown fields')
    if rule.get('format') not in (None, 'uuid', 'date-time'):
        raise ValueError('Unsupported HTTP string format')
    if '$ref' in rule and rule['$ref'] != 'events-v1.json' and not rule['$ref'].startswith('#/$defs/'):
        raise ValueError('Unsupported HTTP schema reference')
    for child in rule.get('properties', {}).values():
        check_rule(child)
    if 'items' in rule:
        check_rule(rule['items'])

def generate(format_go=True):
    schema = json.loads((ROOT / 'schema/internal-http-v1.json').read_text())
    go = ['// Code generated by scripts/generate_http.py; DO NOT EDIT.', 'package internalhttp', '', 'import (', '    "encoding/json"', '    "time"', ')', '']
    rust = ['// Code generated by scripts/generate_http.py; DO NOT EDIT.', 'use chrono::{DateTime, Utc};', 'use serde::{Deserialize, Deserializer, Serialize, Serializer};', 'use uuid::Uuid;', '']
    for typename, definition in schema['$defs'].items():
        check_rule(definition)
        if definition['type'] == 'array':
            go += [f'type {typename} {go_type(definition)}', '']
            rust += [f'pub type {typename} = {rust_type(definition)};', '']
        else:
            go += [f'type {typename} struct {{']
            rust += ['#[derive(Debug, Clone)]', f'pub struct {typename} {{']
            wire = ['#[derive(Deserialize)]', '#[serde(deny_unknown_fields)]', f'struct Wire{typename} {{']
            for field, rule in definition.get('properties', {}).items():
                optional = field not in definition.get('required', [])
                gt, rt = go_type(rule), rust_type(rule)
                if optional or nullable(rule):
                    if gt != 'json.RawMessage':
                        gt = '*' + gt
                    rt = 'Option<' + rt + '>'
                suffix = ',omitempty' if optional else ''
                go += [f'    {name(field)} {gt} `json:"{field}{suffix}"`']
                rust += [f'    pub {field}: {rt},']
                wire += [f'    {field}: {rt},']
            go += ['}', '']
            rust += ['}', ''] + wire + ['}', '']
            wire_binding = 'wire' if definition.get('properties') else '_wire'
            rust += [f"impl<'de> Deserialize<'de> for {typename} {{", '    fn deserialize<D: Deserializer<\'de>>(deserializer: D) -> Result<Self, D::Error> {', '        let value = serde_json::Value::deserialize(deserializer)?;', f'        crate::http_validation::validate("{typename}", &value).map_err(serde::de::Error::custom)?;', f'        let {wire_binding}: Wire{typename} = serde_json::from_value(value).map_err(serde::de::Error::custom)?;', '        Ok(Self {']
            for field in definition.get('properties', {}):
                rust += [f'            {field}: wire.{field},']
            rust += ['        })', '    }', '}', '']
            mutable = 'mut ' if definition.get('properties') else ''
            rust += [f'impl Serialize for {typename} {{', '    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {', f'        let {mutable}fields = serde_json::Map::new();']
            for field, field_rule in definition.get('properties', {}).items():
                optional = field not in definition.get('required', [])
                copy_leaf = rust_type(field_rule) in ('i64', 'bool', 'Uuid', 'DateTime<Utc>')
                borrow = '' if copy_leaf else '&'
                if optional:
                    rust += [f'        if let Some(value) = {borrow}self.{field} {{', f'            fields.insert("{field}".into(), serde_json::to_value(value).map_err(serde::ser::Error::custom)?);', '        }']
                else:
                    rust += [f'        fields.insert("{field}".into(), serde_json::to_value({borrow}self.{field}).map_err(serde::ser::Error::custom)?);']
            rust += ['        let value = serde_json::Value::Object(fields);', f'        crate::http_validation::validate("{typename}", &value).map_err(serde::ser::Error::custom)?;', '        value.serialize(serializer)', '    }', '}', '']
        go += [f'func (v *{typename}) UnmarshalJSON(data []byte) error {{', f'    if err := validateHTTP("{typename}", data); err != nil {{ return err }}', f'    type wire {typename}', '    var decoded wire', '    if err := json.Unmarshal(data, &decoded); err != nil { return err }', f'    *v = {typename}(decoded)', '    return nil', '}', '', f'func (v {typename}) MarshalJSON() ([]byte, error) {{', f'    type wire {typename}', '    data, err := json.Marshal(wire(v))', '    if err != nil { return nil, err }', f'    if err := validateHTTP("{typename}", data); err != nil {{ return nil, err }}', '    return data, nil', '}', '']
    go += ['const CanonicalSchema = `' + json.dumps(schema, separators=(',', ':')) + '`', '']
    rust += ['pub const CANONICAL_SCHEMA: &str = r###"' + json.dumps(schema, separators=(',', ':')) + '"###;', '']
    for path, lines in [('gen/go/internalhttp/types.go', go), ('rust/src/http.rs', rust)]:
        target = ROOT / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text('\n'.join(lines))
    if format_go:
        subprocess.run(['gofmt', '-w', str(ROOT / 'gen/go/internalhttp/types.go')], check=True)

if __name__ == '__main__':
    generate()
