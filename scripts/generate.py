#!/usr/bin/env python3
"""Generate dependency-free DTO definitions from the canonical schema (Python 3.10+)."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schema = json.loads((root / 'schema/events-v1.json').read_text())

def go_name(name):
    return ''.join({'id': 'ID', 'ip': 'IP', 'mfa': 'MFA'}.get(part, part.title()) for part in name.split('_'))

def go_type(rule):
    if rule.get('format') == 'date-time':
        return 'time.Time'
    return {'string': 'string', 'boolean': 'bool', 'integer': 'int'}[rule['type']]

def rust_type(rule):
    if rule.get('format') == 'date-time':
        return 'DateTime<Utc>'
    if rule.get('format') == 'uuid':
        return 'Uuid'
    return {'string': 'String', 'boolean': 'bool', 'integer': 'i64'}[rule['type']]

go = ['// Code generated by scripts/generate.py; DO NOT EDIT.', 'package events', '', 'import "time"', '']
rs = ['// Code generated by scripts/generate.py; DO NOT EDIT.', 'use chrono::{DateTime, Utc};', 'use serde::{Deserialize, Serialize};', 'use uuid::Uuid;', '']
for name, definition in schema['$defs'].items():
    go += [f'type {name} struct {{']
    rs += ['#[derive(Debug, Clone, Serialize, Deserialize)]', '#[serde(deny_unknown_fields)]', f'pub struct {name} {{']
    for field, rule in definition['properties'].items():
        go += [f'    {go_name(field)} {go_type(rule)} `json:"{field}"`']
        rs += [f'    pub {field}: {rust_type(rule)},']
    go += ['}', '']
    rs += ['}', '']
go += ['var payloadDefinitions = map[string]string{']
for name, definition in schema['$defs'].items():
    go += [f'    "{definition["x-event-type"]}": "{name}",']
go += ['}', '', 'const canonicalSchema = ' + '`' + json.dumps(schema, separators=(',', ':')) + '`', '']
rs += ['pub(crate) fn payload_definition(event_type: &str) -> Option<&\'static str> {', '    match event_type {']
for name, definition in schema['$defs'].items():
    rs += [f'        "{definition["x-event-type"]}" => Some("{name}"),']
rs += ['        _ => None,', '    }', '}', '', 'pub const CANONICAL_SCHEMA: &str = r###"' + json.dumps(schema, separators=(',', ':')) + '"###;', '']
for path, lines in [('gen/go/events/types.go', go), ('rust/src/types.rs', rs)]:
    destination = root / path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines))
subprocess.run(['gofmt', '-w', str(root / 'gen/go/events/types.go')], check=True)
from generate_http import generate as generate_http
generate_http()
subprocess.run(['rustfmt', '+1.99.0', '--edition', '2021', str(root / 'rust/src/types.rs'), str(root / 'rust/src/http.rs')], check=True)
from generate_v2 import generate as generate_v2
generate_v2()
v2_go = [str(path) for package in ('businessv1', 'internalhttpv2', 'eventsv2', 'wire') for path in (root / 'gen/go' / package).glob('*.go')]
subprocess.run(['gofmt', '-w', *v2_go], check=True)
v2_rust = [str(path) for path in (root / 'rust/src').glob('*v2*.rs')] + [str(root / 'rust/src/businessv1.rs'), str(root / 'rust/src/businessv1_types.rs')]
subprocess.run(['rustfmt', '+1.99.0', '--edition', '2021', *v2_rust], check=True)
